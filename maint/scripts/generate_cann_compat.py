"""Generate the scoped template macros from the Ascend CANN name lists."""

import argparse
import os
from pathlib import Path
import shlex
import subprocess


ASCEND = Path(__file__).resolve().parents[2] / "src/tl_templates/ascend"
OUTPUT = ASCEND / "cann_compat_begin.h"


def aliases(names, *, types=False):
    lines = []
    for name in names:
        define = f"#define asc_{name}" if types else f"#define asc_{name}(...)"
        target = f"tl::cann::{name}" if types else f"tl::cann::{name}(__VA_ARGS__)"
        lines.append(f"#undef asc_{name}")
        if len(define) + 1 + len(target) > 80:
            lines.extend([define.ljust(79) + "\\", "  " + target])
        else:
            lines.append(f"{define} {target}")
    return "\n".join(lines)


def generate():
    # Let the preprocessor expand the same lists that codegen and the SDK wrappers use.
    source = """\
#include "cann_compat_names.h"
#define NAME(name) name
TL_CANN_TYPE_NAMES(NAME); TL_CANN_CORE_NAMES(NAME); TL_CANN_SIMD_NAMES(NAME)
"""
    command = [*shlex.split(os.environ.get("CC", "cc")), "-E", "-P", "-x", "c", "-I", str(ASCEND), "-"]
    names = subprocess.check_output(command, input=source, text=True)
    types, core, simd = (group.split() for group in names.split(";"))
    return f"""\
// Generated by maint/scripts/generate_cann_compat.py from cann_compat_names.h.
// Include after SDK headers, around TileLang-owned device definitions only.
#include "tl_templates/ascend/cann_compat.h"

#if defined(__NPU_ARCH__)
#define TL_CANN_SCOPE push_macro
#include "tl_templates/ascend/cann_compat_names.inc"
#undef TL_CANN_SCOPE

{aliases(types, types=True)}
{aliases(core)}

#if defined(TL_CANN_SIMD_SCOPE)
{aliases(simd)}
#endif
#endif
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report a stale header without updating it")
    args = parser.parse_args()
    header = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != header:
            parser.exit(1, "Run python maint/scripts/generate_cann_compat.py to update cann_compat_begin.h\n")
    else:
        OUTPUT.write_text(header)
