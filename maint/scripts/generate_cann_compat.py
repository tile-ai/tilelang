"""Generate the preprocessor isolation around TileLang-owned device templates."""

import argparse
import os
from pathlib import Path
import shlex
import subprocess


ASCEND = Path(__file__).resolve().parents[2] / "src/tl_templates/ascend"
OUTPUT = ASCEND / "cann_compat_begin.h"


def generate():
    source = """\
#include "cann_compat_names.h"
#define SDK_NAME(name) asc_##name
TL_CANN_SDK_NAMES(SDK_NAME)
"""
    command = [*shlex.split(os.environ.get("CC", "cc")), "-E", "-P", "-x", "c", "-I", str(ASCEND), "-"]
    names = subprocess.check_output(command, input=source, text=True).split()
    return "\n".join(
        [
            "// Generated by maint/scripts/generate_cann_compat.py. Intentionally repeatable.",
            '#include "tl_templates/ascend/cann_compat.h"',
            "",
            "// Save and clear caller macros before looking up SDK names in C++.",
            "#if defined(__NPU_ARCH__)",
            "TL_CANN_SDK_NAMES(TL_CANN_PUSH_SDK)",
            *(f"#undef {name}" for name in names),
            "#endif",
            "",
        ]
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != header:
            parser.exit(1, "Run python maint/scripts/generate_cann_compat.py to update cann_compat_begin.h\n")
    else:
        OUTPUT.write_text(header)
