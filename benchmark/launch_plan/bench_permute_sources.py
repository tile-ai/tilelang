"""Paired GPU-only comparison of saved Off, #3267, dynamic and Const CUDA sources.

Generate Off/on/Const sources with bench_permute_scales.py; --reference points
at CUDA sources generated by #3267 with its optimization enabled.
"""

import argparse
import ctypes as C
import gc
import json
import random
import re
import statistics
from pathlib import Path

import torch
from tilelang.contrib.nvcc import compile_cuda, default_compile_options
from bench_permute_scales import ref_permute, _flags


def check(code):
    if code:
        raise RuntimeError(f"CUDA driver error {code}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--sources", type=Path, required=True)
    parser.add_argument("--reference", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--count", type=int, default=64)
    parser.add_argument("--rounds", type=int, default=21)
    args = parser.parse_args()
    torch.cuda.init()
    torch.empty(1, device="cuda")
    driver = C.CDLL("libcuda.so.1")
    load = driver.cuModuleLoadData
    load.argtypes = [C.POINTER(C.c_void_p), C.c_void_p]
    get = driver.cuModuleGetFunction
    get.argtypes = [C.POINTER(C.c_void_p), C.c_void_p, C.c_char_p]
    launch = driver.cuLaunchKernel
    launch.argtypes = [C.c_void_p] + [C.c_uint] * 7 + [C.c_void_p, C.POINTER(C.c_void_p), C.c_void_p]
    root = args.output
    root.mkdir(parents=True, exist_ok=True)
    binaries = {}
    for pattern in ["dsv3_w4a16", "dsv3_w4a8", "llama4_w4a16"]:
        for mode in ["off", "magic", "on", "const"]:
            if mode == "magic":
                reference_pattern = "dsv3_w4a16" if pattern == "llama4_w4a16" else pattern
                path = args.reference / f"{reference_pattern}_on.cu"
            else:
                path = args.sources / f"{pattern}_{mode}.cu"
            source = path.read_text()
            print("compile", pattern, mode, flush=True)
            binary = compile_cuda(source, target_format="cubin", arch="sm_120", options=default_compile_options(["--use_fast_math"]))
            (root / f"{pattern}_{mode}.cubin").write_bytes(binary)
            storage = C.create_string_buffer(bytes(binary))
            module = C.c_void_p()
            check(load(C.byref(module), storage))
            function = C.c_void_p()
            check(get(C.byref(function), module, b"permute_moe_mxfp4_scales_kernel"))
            sig = re.search(r"__global__ void \w+\((.*?)\);", source).group(1)
            binaries[pattern, mode] = (
                function,
                module,
                [a.strip().split()[-1] for a in sig.split(",")],
                [a.strip().split()[0] for a in sig.split(",")],
                source,
            )
    resources = {}
    attribute = driver.cuFuncGetAttribute
    attribute.argtypes = [C.POINTER(C.c_int), C.c_int, C.c_void_p]
    for (pattern, mode), entry in binaries.items():
        item = {}
        for attr, name in [(4, "registers"), (3, "local_bytes"), (1, "shared_bytes")]:
            value = C.c_int()
            check(attribute(C.byref(value), attr, entry[0]))
            item[name] = value.value
        resources[pattern + "_" + mode] = item
    (root / "resources.json").write_text(json.dumps(resources, indent=2))
    records = []
    for name, e, n, k, g, a8 in [
        ("dsv3_w4a16", 256, 2048, 7168, 32, False),
        ("dsv3_w4a8", 256, 2048, 7168, 32, True),
        ("llama4_w4a16", 8, 4096, 8192, 128, False),
    ]:
        ng = k // g
        full, quad = _flags(k, g, a8)
        torch.manual_seed(42)
        x = torch.randint(0, 256, (e, n, ng), device="cuda", dtype=torch.uint8)
        y = torch.empty((e, ng, n), device="cuda", dtype=torch.uint8)
        expected = ref_permute(x, n, full, quad)
        pattern = name
        values = {
            "in_scales": C.c_void_p(x.data_ptr()),
            "out_scales": C.c_void_p(y.data_ptr()),
            "num_experts": C.c_int(e),
            "num_groups": C.c_int(ng),
            "size_n": C.c_int(n),
        }
        for i, d in enumerate([ng * n, n]):
            shift = (d - 1).bit_length() - 1
            m = ((1 << (32 + shift)) + d - 1) // d
            suffix = "" if i == 0 else "_1"
            values["fastdiv_multiplier" + suffix] = C.c_uint(m)
            values["fastdiv_shift" + suffix] = C.c_int(shift)
            values["barrett_reciprocal" + suffix] = C.c_int64((1 << 64) // d)
            values["tl_magic_m_" + str(i)] = C.c_int(m)
            values["tl_magic_s_" + str(i)] = C.c_int(shift)
        variants = []
        for mode in ["off", "magic", "on", "const"]:
            function, _, names, types, source = binaries[pattern, mode]
            mode_values = values.copy()
            for match in re.finditer(r"tl::(?:fast_div|fast_rem|barrett_reduce)\(", source):
                start = match.end()
                depth = 0
                operands = []
                last = start
                for pos in range(start, len(source)):
                    c = source[pos]
                    if c == "(":
                        depth += 1
                    elif c == ")":
                        if depth == 0:
                            operands.append(source[last:pos].strip())
                            break
                        depth -= 1
                    elif c == "," and depth == 0:
                        operands.append(source[last:pos].strip())
                        last = pos + 1
                divisor = ng * n if "num_groups" in operands[1] else n
                reciprocal = re.search(r"(?:barrett_reciprocal|fastdiv_multiplier)\w*", operands[2])
                if not reciprocal:
                    continue
                param = reciprocal.group()
                if param.startswith("barrett"):
                    ctype = types[names.index(param)]
                    mode_values[param] = (C.c_uint if ctype == "uint" else C.c_int64)((1 << (32 if ctype == "uint" else 64)) // divisor)
                else:
                    shift = (divisor - 1).bit_length() - 1
                    mode_values[param] = C.c_uint(((1 << (32 + shift)) + divisor - 1) // divisor)
                    mode_values[operands[3]] = C.c_int(shift)
            params = (C.c_void_p * len(names))(*[C.addressof(mode_values[n]) for n in names])

            def call(function=function, params=params, mode_values=mode_values, grid=(e * n * ng + 255) // 256):
                check(
                    launch(
                        function,
                        grid,
                        1,
                        1,
                        256,
                        1,
                        1,
                        0,
                        C.c_void_p(torch.cuda.current_stream().cuda_stream),
                        params,
                        None,
                    )
                )

            call()
            torch.cuda.synchronize()
            torch.testing.assert_close(y, expected, rtol=0, atol=0)
            graph = torch.cuda.CUDAGraph()
            with torch.cuda.graph(graph):
                for _ in range(args.count):
                    call()
            y.copy_(expected ^ 255)
            graph.replay()
            torch.cuda.synchronize()
            torch.testing.assert_close(y, expected, rtol=0, atol=0)
            variants.append((mode, graph))
        samples = {mode: [] for mode, _ in variants}
        rng = random.Random(3267)
        for _, graph in variants:
            for _ in range(5):
                graph.replay()
        torch.cuda.synchronize()
        for _ in range(args.rounds):
            order = list(variants)
            rng.shuffle(order)
            for mode, graph in order:
                start, end = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
                start.record()
                for _ in range(5):
                    graph.replay()
                end.record()
                end.synchronize()
                samples[mode].append(start.elapsed_time(end) * 1000 / (args.count * 5))
        for mode, _ in variants:
            row = dict(case=name, mode=mode, gpu_us=statistics.median(samples[mode]), samples=samples[mode])
            records.append(row)
            print(row, flush=True)
        (root / "results.json").write_text(
            json.dumps(dict(device=torch.cuda.get_device_name(), count=args.count, rounds=args.rounds, results=records), indent=2)
        )
        del variants, graph, call, x, y, expected
        gc.collect()
        torch.cuda.empty_cache()


if __name__ == "__main__":
    main()
